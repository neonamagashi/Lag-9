"""Tiny Elder Futhark glyphs (5x7, white) for her spells, in one strip of 7x9 cells."""
from PIL import Image, ImageDraw

RUNES = {
    "fehu": [((1, 0), (1, 6)), ((1, 2), (3, 0)), ((1, 4), (3, 2))],
    "uruz": [((1, 6), (1, 0)), ((1, 0), (3, 2)), ((3, 2), (3, 6))],
    "thurisaz": [((1, 0), (1, 6)), ((1, 2), (3, 3)), ((3, 3), (1, 4))],
    "ansuz": [((1, 0), (1, 6)), ((1, 0), (3, 2)), ((1, 2), (3, 4))],
    "raidho": [((1, 0), (1, 6)), ((1, 0), (3, 1)), ((3, 1), (1, 3)), ((1, 3), (3, 6))],
    "kenaz": [((3, 0), (1, 3)), ((1, 3), (3, 6))],
    "gebo": [((0, 0), (4, 6)), ((4, 0), (0, 6))],
    "wunjo": [((1, 0), (1, 6)), ((1, 0), (3, 1)), ((3, 1), (1, 3))],
    "hagalaz": [((0, 0), (0, 6)), ((4, 0), (4, 6)), ((0, 2), (4, 4))],
    "naudiz": [((2, 0), (2, 6)), ((0, 2), (4, 4))],
    "isa": [((2, 0), (2, 6))],
    "jera": [((2, 0), (0, 2)), ((0, 2), (2, 4)), ((2, 2), (4, 4)), ((4, 4), (2, 6))],
    "eihwaz": [((2, 0), (2, 6)), ((2, 0), (3, 1)), ((2, 6), (1, 5))],
    "algiz": [((2, 0), (2, 6)), ((2, 2), (0, 0)), ((2, 2), (4, 0))],
    "sowilo": [((3, 0), (1, 2)), ((1, 2), (3, 4)), ((3, 4), (1, 6))],
    "tiwaz": [((2, 0), (2, 6)), ((2, 0), (0, 2)), ((2, 0), (4, 2))],
    "berkano": [((1, 0), (1, 6)), ((1, 0), (3, 1)), ((3, 1), (1, 3)), ((1, 3), (3, 5)), ((3, 5), (1, 6))],
    "mannaz": [((0, 0), (0, 6)), ((4, 0), (4, 6)), ((0, 0), (4, 3)), ((4, 0), (0, 3))],
    "othala": [((2, 0), (0, 2)), ((0, 2), (2, 4)), ((2, 4), (4, 2)), ((4, 2), (2, 0)), ((1, 3), (0, 6)), ((3, 3), (4, 6))],
}

strip = Image.new("RGBA", (7 * len(RUNES), 9))
d = ImageDraw.Draw(strip)
for i, lines in enumerate(RUNES.values()):
    for a, b in lines:
        d.line([(i * 7 + 1 + a[0], 1 + a[1]), (i * 7 + 1 + b[0], 1 + b[1])], fill=(255, 255, 255, 255))
strip.save("assets/vfx/runes.png")
print(len(RUNES), "runes")
